async (page) => {
  const results=[], errors=[], external=[], failed=[];
  const check=(name,condition,detail)=>{if(!condition)throw new Error(name);results.push({name,pass:true,detail});};
  const context=page.context();
  await context.route('**/*',route=>{const url=new URL(route.request().url());if(url.hostname==='127.0.0.1')return route.continue();external.push(url.href);return route.abort();});
  page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.status()>=400)failed.push({url:r.url(),status:r.status()});});
  await page.setViewportSize({width:1536,height:960});
  await page.goto('http://127.0.0.1:4179/');
  await page.getByRole('button',{name:'◎ 全部灯具 215',exact:true}).waitFor();
  check('root build with external network blocked',true);
  check('production debug API excluded',await page.evaluate(()=>!window.__CJT));
  await page.getByRole('textbox',{name:'当前工程',exact:true}).fill('QA isolated browser');
  await page.getByRole('textbox',{name:'当前工程',exact:true}).press('Tab');
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.reload();await page.getByRole('button',{name:'◎ 全部灯具 215',exact:true}).waitFor();
  check('production refresh persistence',await page.getByRole('textbox',{name:'当前工程',exact:true}).inputValue()==='QA isolated browser');
  const isolated=await context.browser().newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  await isolated.route('**/*',r=>new URL(r.request().url()).hostname==='127.0.0.1'?r.continue():r.abort());
  const phone=await isolated.newPage();await phone.goto('http://127.0.0.1:4179/');
  await phone.getByRole('button',{name:'布局',exact:true}).tap();
  await phone.getByRole('button',{name:'面光 L01 正常',exact:true}).waitFor();
  check('isolated browser does not share practice',await phone.evaluate(()=>!localStorage.getItem('CUNJUTANG_SHOW_V1')?.includes('QA isolated browser')));
  await phone.getByRole('button',{name:'面光 L01 正常',exact:true}).tap();
  check('touch selection opens controls',await phone.getByRole('slider',{name:'亮度',exact:true}).isVisible());
  await phone.getByRole('button',{name:'100%',exact:true}).tap();
  check('touch dimmer preset',await phone.getByRole('slider',{name:'亮度',exact:true}).inputValue()==='255');
  await phone.screenshot({path:'output/playwright/production-touch.png'});await isolated.close();
  await page.locator('input[type=file]').setInputFiles({name:'broken.json',mimeType:'application/json',buffer:Buffer.from('{bad file')});
  await page.getByRole('alert').waitFor();
  check('corrupt import keeps project',await page.getByRole('textbox',{name:'当前工程',exact:true}).inputValue()==='QA isolated browser');
  const errorText=await page.getByRole('alert').textContent();results.push({name:'corrupt file message',detail:errorText});
  await page.getByRole('alert').getByRole('button').click();
  await page.locator('input[type=file]').setInputFiles('public/teaching/cunjutang.showfile.json');
  await page.waitForFunction(()=>document.querySelector('.toast')?.textContent.includes('工程已导入'));
  await page.getByRole('button',{name:'调用 ↗',exact:true}).first().click();
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.goto('http://127.0.0.1:4180/rehearsal');
  await page.getByRole('button',{name:'◎ 全部灯具 215',exact:true}).waitFor();
  check('subpath redirects and loads assets',page.url()==='http://127.0.0.1:4180/rehearsal/');
  check('no failed static resources',failed.length===0,failed);
  check('no external resources attempted',external.length===0,external);
  check('no uncaught errors',errors.length===0,errors);
  await page.screenshot({path:'output/playwright/production-subpath.png'});
  await page.evaluate(r=>{window.productionTestResults=r;},results);
  return results;
}
